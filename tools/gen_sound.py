#!/usr/bin/env python3
"""Generate build/port/sound_tabs.inc for the port's sound driver (src/sound.asm)
from the arcade sound ROM (build/arcade/sound.bin, 16 KB, identical to cm02.9f):

- snd_cmd_tab: the 47 sound commands ($00-$2E) as (type, parameter, pointer):
  0 stop all effects, 1 effect (parameter = slot 0-7: chip 1 slots 0-3, chip 2
  slots 4-7; pointer = script), 2 music (parameter = group 0-3; pointer =
  header), 3 stop the music. Pointers are sound ROM addresses | $4000 (the
  ROM is mapped on page 1).
- opl_note_tab and opl4_note_tab: the 97 arcade pitches at the respective
  YMF262 and YMF278B FM clocks, as register values for $A0 (F-number low)
  and $B0 (block and F-number high, key-on bit clear).
- opl_patch_tab: the 32 YM2203 patches converted to OPL3 4-operator
  channels: per operator (OPL3 op 1-4) the $20, $40, $60, $80 register bytes,
  then the $C0 bytes of the two 2-op channels of the pair (feedback,
  connection, L + R).

YM2203 -> OPL3: preserve the operator multiplier codes, attenuation (clipped
at 63) and sustain levels. Convert envelope rates for the faster OPL envelope
clock. Key scaling 2-3 -> KSR; detune and AM are lost; a
non-zero sustain rate becomes a non-sustaining envelope whose release is
that rate (the note keeps decaying while held, as on the OPN). Algorithms:
0-3 -> the serial chain (1-3 approximated), 4 -> (1>2) + (3>4), 6 -> 1 +
(2>3) + 4 with the operators reordered. The music uses neither 5 nor 7.
Operators outside the patch's key-on mask get TL 63 and attack rate zero.
"""
import sys


def opl_rate(effective_rate):
    """Convert the OPN's six-bit base rate to an OPL envelope rate nibble."""
    if effective_rate == 0:
        return 0
    # OPL advances envelopes every sample, OPN every third sample. At
    # these chip clocks two OPL rate steps compensate for the faster EG.
    return max(1, min(15, (effective_rate - 8 + 2) // 4))


def main():
    rom = open(sys.argv[1], 'rb').read()
    out = sys.argv[2]
    assert len(rom) == 16384
    w16 = lambda a: rom[a] | rom[a + 1] << 8
    o = ['; generated by tools/gen_sound.py from the arcade sound ROM']
    # ---- commands
    o.append('snd_cmd_tab:')
    for c in range(0x2F):
        h = w16(0x88 + 2 * c)
        if c == 0 or 0x1C <= c <= 0x1F:
            o.append('        db 0,0,0,0')
        elif c < 0x1C:
            slot = w16(h + 2)
            p = w16(h + 5) | 0x4000
            idx = ((slot >> 8) - 0x45) * 4 + ((slot & 0xFF) >> 5)
            o.append('        db 1,%d,0%02Xh,0%02Xh      ; $%02X' % (idx, p & 255, p >> 8, c))
        elif c <= 0x2C:
            grp = {0x1F7: 0, 0x200: 1, 0x209: 2}[w16(h + 1)]
            p = w16(h + 4) | 0x4000
            o.append('        db 2,%d,0%02Xh,0%02Xh      ; $%02X' % (grp, p & 255, p >> 8, c))
        else:
            o.append('        db 3,0,0,0')
    # Commando selects prescaler /3 on both 1.5 MHz YM2203s. Their
    # F-number unit at block zero is 1.5 MHz / (72 * 2**20).
    for label, fm_rate in (('opl_note_tab', 14318180 / 288),
                           ('opl4_note_tab', 33868800 / 684)):
        o.append(label + ':')
        for k in range(97):
            offset = 0x0135 + 2 * k
            opn = int.from_bytes(rom[offset:offset + 2], 'big')
            scaled = (opn & 0x7FF) * (1 << (opn >> 11)) * (1500000 / 72) / fm_rate
            for block in range(8):
                fnum = round(scaled / (1 << block))
                if fnum < 1024:
                    break
            assert 0 <= fnum < 1024
            o.append('        db 0%02Xh,0%02Xh          ; entry %d' %
                     (fnum & 255, block << 2 | fnum >> 8, k))
    # ---- patches
    # YM2203 patch bytes 0-23 are in register order: slots S1, S3, S2, S4
    SLOT = (0, 2, 1, 3)        # register index -> slot number S1..S4 (0-based)
    # OPL3 4-op connection (CNT of channel A, CNT of channel B) and the slot of each OPL3 operator 1-4
    ALG = {0: ((0, 0), (0, 1, 2, 3)), 1: ((0, 0), (0, 1, 2, 3)), 2: ((0, 0), (0, 1, 2, 3)),
           3: ((0, 0), (0, 1, 2, 3)), 4: ((0, 1), (0, 1, 2, 3)), 5: ((0, 0), (0, 1, 2, 3)),
           6: ((1, 1), (2, 0, 1, 3)), 7: ((1, 1), (0, 1, 2, 3))}
    o.append('opl_patch_tab:')
    for n in range(32):
        p = rom[0x0AA7 + 32 * n:0x0AA7 + 32 * n + 32]
        fld = {}            # slot -> (dtmul, tl, ksar, dr, sr, slrr)
        for i in range(4):
            fld[SLOT[i]] = (p[i], p[4 + i], p[8 + i], p[12 + i], p[16 + i], p[20 + i])
        alg, fb = p[24] & 7, (p[24] >> 3) & 7
        mask = p[25] >> 4           # key-on bits: b0 S1, b1 S2, b2 S3, b3 S4
        (cnta, cntb), order = ALG[alg]
        # Algorithm 6 moves S1 to OPL operator 2. Feedback is available
        # only on operator 1, which now carries an independent audible voice.
        if alg == 6:
            fb = 0
        regs = []
        for op in range(4):
            s = order[op]
            dtmul, tl, ksar, dr, sr, slrr = fld[s]
            mul = dtmul & 15
            # Both chips attenuate by 0.75 dB per TL step. On a modulator
            # this sets the harmonic content as well as the operator level.
            tl = min(tl & 0x7F, 63)
            enabled = (mask >> s) & 1
            if not enabled:
                tl = 63
            ks, ar = ksar >> 6, ksar & 31
            dr &= 31
            sr &= 31
            sl, rr = slrr >> 4, slrr & 15
            eg = int(sr == 0)
            release = opl_rate(2 * sr if sr else 4 * rr + 2)
            r20 = eg << 5 | (1 if ks >= 2 else 0) << 4 | mul
            r40 = tl
            attack = 15 if ar >= 30 else opl_rate(2 * ar)
            if not enabled:
                attack = 0
            r60 = attack << 4 | opl_rate(2 * dr)
            r80 = sl << 4 | release
            regs += [r20, r40, r60, r80]
        regs += [0x30 | fb << 1 | cnta, 0x30 | cntb]
        o.append('        db ' + ','.join('0%02Xh' % v for v in regs) + '   ; patch %d: alg %d fb %d' % (n, alg, fb))
    with open(out, 'w') as f:
        f.write('\n'.join(o) + '\n')


if __name__ == '__main__':
    main()
