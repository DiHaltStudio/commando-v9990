#!/usr/bin/env python3
"""Generate build/port/spat_chain.inc: the unrolled scan of the 96 arcade
sprite entries for build_spat (overlay.asm). Per entry: read its Y byte at an
absolute address (0 = hidden, 27 T and on to the next), else call spat_vis
with the entry in registers: L = code, H = attribute, E = Y byte (the V9990
X), D = X byte (the line), B = entry number. The chain runs entries 0-95 in
order (the structures' 36 entries cannot be skipped: the map objects use
entries 1-53 too).
"""
import sys

SPRITERAM = 0xFE00
ENTRIES = 96


def main():
    out = sys.argv[1]
    o = ['; generated by tools/gen_spat.py: the unrolled sprite entry scan of build_spat',
         'spat_chain:']
    for n in range(ENTRIES):
        addr = SPRITERAM + 4 * n
        o.append('spe%d:' % n)            # (the label first: a hidden entry jumps here)
        o.append('        ld a,(0%04Xh)' % (addr + 2))
        o.append('        or a')
        o.append('        jp z,spe%d' % (n + 1))
        o.append('        ld e,a')
        o.append('        ld a,(0%04Xh)' % (addr + 3))
        o.append('        ld d,a')
        o.append('        ld hl,(0%04Xh)' % addr)
        o.append('        ld b,%d' % n)
        o.append('        call spat_vis')
    o.append('spe%d:' % ENTRIES)
    o.append('        ret')
    with open(out, 'w') as f:
        f.write('\n'.join(o) + '\n')


if __name__ == '__main__':
    main()
