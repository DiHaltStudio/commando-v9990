#!/usr/bin/env python3
"""Generate build/port/bgobj_slots.inc: the per-slot blocks of ovl_bgobj_all
(overlay.asm), one per map structure slot of bgobj_slots, with the slot, its
record and its hit list position as absolute addresses (the loop version
cost ~500 T per active slot in IX-indexed accesses; this one ~320 T).

Conventions (see ovl_bgobj_all): B = scroll delta of the tick (0 or 1), DE =
hit list write pointer, bgo_full (IX = slot, HL = record) and bgo_debris
(IX = slot, A = slot offset) are the shared slow paths.
"""
import sys

SLOTS = 9
SLOT_BASE = 0xE800      # bgobj_slots, 16 bytes each
REC_BASE = 0xFD80       # bgo_rec, 8 bytes each
HIT_SLOTS = 8           # the arcade hit-tests the first 8 slots only


def block(n):
    s = SLOT_BASE + 16 * n
    r = REC_BASE + 8 * n
    L = 'bgs%d_' % n
    o = []
    a = o.append
    a('; ---- slot %d: $%04X, record $%04X' % (n, s, r))
    a('        ld a,(0%04Xh)' % s)
    a('        or a')
    a('        jp z,%send' % L)
    a('        inc a')
    a('        jp nz,%sdebris' % L)
    a('        ld hl,(0%04Xh)          ; L = y high, H = y low' % (s + 4))
    a('        ld a,b')
    a('        or a')
    a('        jr z,%skeep' % L)
    a('        ld a,h                  ; y - 1 (the map moved)')
    a('        sub 1')
    a('        ld h,a')
    a('        jr nc,%sstore' % L)
    a('        dec l')
    a('%sstore:' % L)
    a('        ld (0%04Xh),hl' % (s + 4))
    a('%skeep:' % L)
    a('        ld a,l                  ; keep while y is 0-$FF or -32..-1')
    a('        or a')
    a('        jr z,%sdraw' % L)
    a('        ld a,h')
    a('        cp 0E0h')
    a('        jr nc,%sdraw' % L)
    a('        xor a')
    a('        ld (0%04Xh),a           ; gone below the screen: free the slot' % s)
    a('        jp %send' % L)
    a('%sdraw:' % L)
    if n < HIT_SLOTS:
        a('        ld a,h                  ; hit list: y, x, solid box offset and width')
        a('        ld (de),a')
        a('        inc e')
        a('        ld a,(0%04Xh)' % (s + 3))
        a('        ld (de),a')
        a('        inc e')
        a('        ld hl,(0%04Xh)' % (s + 9))
        a('        ld a,l')
        a('        ld (de),a')
        a('        inc e')
        a('        ld a,h')
        a('        ld (de),a')
        a('        inc e')
    a('        ld a,(bgo_dirty)')
    a('        or a')
    a('        jp nz,%sfull' % L)
    a('        ld a,(0%04Xh)           ; seen byte of the record' % (r + 5))
    a('        cp 2')
    a('        jp z,%sfull              ; a new structure took the slot' % L)
    a('        ld a,1')
    a('        ld (0%04Xh),a           ; seen' % (r + 5))
    a('        ld a,(0%04Xh)' % r)
    a('        or a')
    a('        jp nz,%send              ; the record has cells' % L)
    a('%sfull:' % L)
    a('        ld a,(bgo_spr+%d)        ; drawn as sprites (bgo_overlap): no cells' % n)
    a('        or a')
    a('        jp nz,%send' % L)
    a('        ld ix,0%04Xh' % s)
    a('        ld hl,0%04Xh' % r)
    a('        call bgo_full')
    a('        jp %send' % L)
    a('%sdebris:' % L)
    a('        ld ix,0%04Xh' % s)
    a('        ld a,%d' % (16 * n))
    a('        call bgo_debris')
    a('%send:' % L)
    return o


def main():
    out = sys.argv[1]
    lines = ['; generated by tools/gen_bgobj.py: the per-slot blocks of ovl_bgobj_all']
    for n in range(SLOTS):
        lines += block(n)
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
